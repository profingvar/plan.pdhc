"""Generate db_schema_snapshot.md from the LIVE database.

#786 item 3c. The committed snapshot was dated 2026-03-20, its header said
"Tables: 17", and the database had 22 -- five tables undocumented for six
months. A hand-maintained schema document drifts by construction, so this
regenerates it instead.

Run it where the database is reachable. In production that is inside the app
container, which already holds DATABASE_URL:

    docker exec -i pdhc_app python - < scripts/gen_db_schema_snapshot.py \
        > db_schema_snapshot.md

It is read-only: information_schema plus one COUNT(*) per table.
"""
from __future__ import annotations

import datetime
import os
import re

import psycopg2


def main() -> None:
    url = os.environ.get("DATABASE_URL", "")
    if not url:
        raise SystemExit("DATABASE_URL is not set")
    # SQLAlchemy-style driver suffixes are not psycopg2 connection syntax.
    conn = psycopg2.connect(re.sub(r"^postgresql\+\w+://", "postgresql://", url))
    cur = conn.cursor()

    cur.execute("""
        SELECT table_name FROM information_schema.tables
        WHERE table_schema = 'public' AND table_type = 'BASE TABLE'
        ORDER BY table_name
    """)
    tables = [r[0] for r in cur.fetchall()]

    cur.execute("""
        SELECT tc.table_name, kcu.column_name, tc.constraint_type,
               ccu.table_name AS ref_table, ccu.column_name AS ref_column
        FROM information_schema.table_constraints tc
        JOIN information_schema.key_column_usage kcu
          ON kcu.constraint_name = tc.constraint_name
         AND kcu.table_schema = tc.table_schema
        LEFT JOIN information_schema.constraint_column_usage ccu
          ON ccu.constraint_name = tc.constraint_name
         AND ccu.table_schema = tc.table_schema
        WHERE tc.table_schema = 'public'
          AND tc.constraint_type IN ('PRIMARY KEY', 'FOREIGN KEY', 'UNIQUE')
    """)
    marks: dict[tuple[str, str], list[str]] = {}
    for t, c, kind, rt, rc in cur.fetchall():
        key = (t, c)
        if kind == 'PRIMARY KEY':
            marks.setdefault(key, []).append('PK')
        elif kind == 'UNIQUE':
            marks.setdefault(key, []).append('unique')
        elif kind == 'FOREIGN KEY' and rt:
            marks.setdefault(key, []).append(f'FK -> {rt}.{rc}')

    counts = {}
    for t in tables:
        cur.execute(f'SELECT count(*) FROM "{t}"')
        counts[t] = cur.fetchone()[0]

    today = datetime.date.today().isoformat()
    out = []
    out.append("# PDHC PlanDef Builder — Database Schema Snapshot")
    out.append("")
    out.append(f"**Generated:** {today} — by `scripts/gen_db_schema_snapshot.py`")
    out.append("**Database:** `pdhc_gateway` (PostgreSQL) — legacy name; see rollup #325 / #336")
    out.append(f"**Tables:** {len(tables)}")
    out.append("")
    out.append("> Generated from the live database, not hand-maintained. The previous")
    out.append("> snapshot was written by hand on 2026-03-20, said \"Tables: 17\", and the")
    out.append("> database had 22. Six were absent, and not at random: the whole")
    out.append("> forms/questionnaire subsystem (`form_definitions`,")
    out.append("> `form_definition_items`, `questionnaires`, `questionnaire_items`,")
    out.append("> `questionnaire_responses`) plus `alembic_version` — while the dashboard")
    out.append("> had been counting Forms on its front page the entire time (#786).")
    out.append("> Refresh by re-running the script; do not edit this file.")
    out.append("")
    out.append("## Tables at a glance")
    out.append("")
    out.append("| table | columns | rows |")
    out.append("|---|---:|---:|")
    for t in tables:
        cur.execute("""SELECT count(*) FROM information_schema.columns
                       WHERE table_schema='public' AND table_name=%s""", (t,))
        out.append(f"| `{t}` | {cur.fetchone()[0]} | {counts[t]} |")
    out.append("")
    out.append("---")
    out.append("")

    for t in tables:
        out.append(f"## `{t}`")
        out.append("")
        out.append(f"{counts[t]} row(s).")
        out.append("")
        out.append("| column | type | null | default | keys |")
        out.append("|---|---|---|---|---|")
        cur.execute("""
            SELECT column_name, data_type, character_maximum_length,
                   is_nullable, column_default
            FROM information_schema.columns
            WHERE table_schema='public' AND table_name=%s
            ORDER BY ordinal_position
        """, (t,))
        for name, dtype, maxlen, nullable, default in cur.fetchall():
            ty = f"{dtype}({maxlen})" if maxlen else dtype
            d = (default or "")
            if len(d) > 34:
                d = d[:31] + "..."
            keys = ", ".join(marks.get((t, name), []))
            out.append(f"| `{name}` | {ty} | {'yes' if nullable == 'YES' else 'no'} "
                       f"| {('`'+d+'`') if d else ''} | {keys} |")
        out.append("")

    print("\n".join(out))
    cur.close()
    conn.close()


if __name__ == "__main__":
    main()
